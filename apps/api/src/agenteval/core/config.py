"""Runtime configuration, validated once at boot.

Every setting comes from the environment. Security-relevant settings are checked by
``Settings.guard`` so a misconfigured production deployment refuses to start instead of
running with demo secrets.
"""

from __future__ import annotations

from functools import lru_cache
from typing import Annotated, Literal

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

INSECURE_SECRETS = {"", "change-me", "replace-with-output-of-make-env", "dev", "secret"}


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=None, extra="ignore", case_sensitive=False)

    environment: Literal["development", "test", "production"] = "development"
    cloud: Literal["local", "floci", "aws"] = Field("local", alias="AGENTEVAL_CLOUD")
    log_level: str = "INFO"

    database_url: str = "postgresql+asyncpg://agenteval:agenteval@localhost:5742/agenteval"
    redis_url: str = "redis://localhost:5779/0"

    # Signing secret for dashboard sessions and pepper for API key hashes. Separate values so
    # rotating sessions does not invalidate every API key.
    session_secret: str = "dev-session-secret-not-for-production"  # noqa: S105 dev default, refused in production by guard()
    api_key_pepper: str = "dev-api-key-pepper-not-for-production"
    session_ttl_hours: int = 12
    cookie_secure: bool = False
    # NoDecode: read the env value as a plain comma-separated string, not JSON.
    cors_origins: Annotated[list[str], NoDecode] = Field(
        default_factory=lambda: ["http://localhost:5710"]
    )

    # The password every seed-demo account shares; generated by scripts/gen-local-env.sh
    # and printed by make demo, never a committed value. AE_DEMO_PASSWORD matches the
    # container env var name set in deploy/compose/compose.yaml.
    demo_password: str = Field("dev-demo-password-not-for-production", alias="AE_DEMO_PASSWORD")

    # The judge provider's own call target. Defaults to the real OpenAI-compatible chat
    # completions shape; MOCK_AI_URL overrides it for local development, the demo and
    # tests, the same convention every mock-service project in this program uses, so no
    # real API key is ever needed to exercise an evaluation end to end.
    mock_ai_url: str | None = None
    openai_api_base_url: str = "https://api.openai.com/v1"
    anthropic_api_base_url: str = "https://api.anthropic.com/v1"

    def judge_base_url(self, provider: str) -> str:
        if self.mock_ai_url:
            return self.mock_ai_url
        if provider == "anthropic":
            return self.anthropic_api_base_url
        return self.openai_api_base_url

    otel_enabled: bool = False

    @field_validator("cors_origins", mode="before")
    @classmethod
    def _split_origins(cls, v: object) -> object:
        if isinstance(v, str):
            return [o.strip() for o in v.split(",") if o.strip()]
        return v

    def guard(self) -> None:
        """Refuse to boot in production with demo secrets or unsafe options."""
        if self.environment != "production":
            return
        problems: list[str] = []
        for name in ("session_secret", "api_key_pepper"):
            value = getattr(self, name)
            if value in INSECURE_SECRETS or "not-for-production" in value or len(value) < 32:
                problems.append(f"{name.upper()} must be a random value of at least 32 chars")
        if self.session_secret == self.api_key_pepper:
            problems.append("SESSION_SECRET and API_KEY_PEPPER must differ")
        if self.cloud == "aws" and self.mock_ai_url:
            problems.append("MOCK_AI_URL must be unset when AGENTEVAL_CLOUD=aws")
        if problems:
            raise RuntimeError("unsafe production configuration: " + "; ".join(problems))


@lru_cache
def get_settings() -> Settings:
    settings = Settings()
    settings.guard()
    return settings
